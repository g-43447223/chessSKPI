let runtimeLanguage = 'ms'

export function normalizeLanguage(value) {
  return String(value ?? '').toLowerCase().startsWith('en') ? 'en' : 'ms'
}

export function getStoredLanguage() {
  try {
    if (typeof localStorage === 'undefined') return 'ms'
    return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY))
  } catch {
    return 'ms'
  }
}

export function persistLanguage(language) {
  try {
    if (typeof localStorage === 'undefined') return
    localStorage.setItem(LANGUAGE_STORAGE_KEY, normalizeLanguage(language))
  } catch {
    /* ignore storage failures — the UI still switches for this session */
  }
}

export function setRuntimeLanguage(language) {
  runtimeLanguage = normalizeLanguage(language)
  return runtimeLanguage
}

export function getLanguage() {
  return runtimeLanguage
}

export function localeFor(language) {
  return normalizeLanguage(language) === 'en' ? 'en-MY' : 'ms-MY'
}

export function translate(language, key, vars = {}) {
  const entry =
    MESSAGES[key] ??
    (vars.count === undefined
      ? undefined
      : MESSAGES[`${key}.${vars.count === 1 ? 'one' : 'other'}`])
  if (!entry) return key

  let value = entry[normalizeLanguage(language)] ?? entry.ms
  if (value && typeof value === 'object') {
    value = vars.count === 1 ? value.one : value.other
  }
  if (value == null) return key

  return String(value).replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] === undefined || vars[name] === null ? match : String(vars[name]),
  )
}

export function t(key, vars = {}) {
  return translate(runtimeLanguage, key, vars)
}

runtimeLanguage = getStoredLanguage()
